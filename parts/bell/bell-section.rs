//! Draw a bell (or the mouthpiece) in axial section, so the inside surface and
//! the outside are both visible. Rust since 2026-11-07 (bell-section.py until
//! then). Ring sizes are read out of the cut file, so this cannot drift from
//! what gets cut. DISPLAY ONLY. Not a cut file.
//!
//!     target/release/bell-section cut-files/bell-round10-153mm-17rings-x3-rim86-cut-files.svg [OUT.svg]
#[path = "../common.rs"]
mod common;
#[path = "../views.rs"]
mod views;
use common::*;
use lasermade_tools::py::{self, g};
use views::*;

/// Every generated bell states its own rise; the mouthpiece does not, and is
/// 3mm ply a ring.
const DEFAULT_RISE: f64 = 3.0;

/// Width of each subpath, whatever commands drew it.
fn subpath_widths(d: &str) -> Vec<f64> {
    sections(d).into_iter().map(|s| s.0).collect()
}

fn ring_sizes(path: &str) -> (Vec<(f64, f64)>, f64) {
    let s = read(path);
    let mut out: Vec<(f64, f64)> = Vec::new();
    // Holes before rims: the aperture and the outline are in different groups,
    // both in ring order, so pair them by position.
    if let (Some(ap_g), Some(out_g)) = (group(&s, "#ff8000"), group(&s, "#000000")) {
        let aps: Vec<Vec<f64>> = lasermade_tools::re::findall1(&lasermade_tools::re::rx(r#"d="([^"]+)""#), ap_g, 1).iter().map(|d| subpath_widths(d)).collect();
        let outs: Vec<Vec<f64>> = lasermade_tools::re::findall1(&lasermade_tools::re::rx(r#"d="([^"]+)""#), out_g, 1).iter().map(|d| subpath_widths(d)).collect();
        for (a, o) in aps.iter().zip(&outs) {
            if a.len() == 1 && o.len() == 1 {
                out.push((a[0], o[0]));
            }
        }
        if !out.is_empty() {
            out.sort_by(|a, b| a.partial_cmp(b).unwrap());
            return (out, rise_of(&s).unwrap_or(3.0));
        }
    }
    // One path, two subpaths: walk the path, never read "M x,y H x2" as the width.
    for d in path_ds(&s) {
        let e = subpath_widths(&d);
        if e.len() == 2 {
            out.push((py::min(e[0], e[1]), py::max(e[0], e[1])));
        }
    }
    out.sort_by(|a, b| a.partial_cmp(b).unwrap());
    (out, rise_of(&s).unwrap_or(DEFAULT_RISE))
}

fn main() {
    let a: Vec<String> = std::env::args().collect();
    if a.len() < 2 {
        exit("  usage: bell-section SHEET.svg [OUT.svg]");
    }
    let src = &a[1];
    let (rings, rise) = ring_sizes(src);
    if rings.is_empty() {
        exit(format!("AssertionError: no rings found in {src}"));
    }
    let dst = if a.len() > 2 { a[2].clone() } else { display_out(src, "-section.svg") };

    let n = rings.len();
    let l = n as f64 * rise;
    let rmax = rings[n - 1].1 / 2.0;
    let (m, scale) = (14.0, 1.0);
    let (w, h) = ((l + 2.0 * m) * scale, (2.0 * rmax + 2.0 * m) * scale);
    let cy = h / 2.0;
    let (wall, bore, axis) = ("#c9a227", "#faf7f0", "#8a8f96");
    let mut body = Vec::new();
    let mut z = 0.0;
    for &(ap, o) in &rings {
        let (ri, ro) = (ap / 2.0, o / 2.0);
        for sgn in [-1.0, 1.0] {
            let y0 = cy + sgn * ri * scale;
            let y1 = cy + sgn * ro * scale;
            body.push(format!(
                "<rect x=\"{:.3}\" y=\"{:.3}\" width=\"{:.3}\" height=\"{:.3}\" fill=\"{wall}\" stroke=\"#6b5416\" stroke-width=\"0.4\"/>",
                m + z * scale,
                py::min(y0, y1),
                rise * scale,
                (y1 - y0).abs()
            ));
        }
        z += rise;
    }
    let name = lasermade_tools::text::pathstr(src).rsplit('/').next().unwrap_or("").to_string();
    let stem = match name.rfind('.') {
        Some(k) if k > 0 => &name[..k],
        _ => &name[..],
    };
    // This draws whatever it is pointed at; it says which.
    let label = if stem.contains("mouthpiece") {
        format!("Axial section of the {n}-ring mouthpiece: the bore narrowing to the throat and opening again, the outside stepping the other way, wall between them")
    } else {
        format!("Axial section of a {n}-ring bell: the bore climbing one staircase and the outside another, wall between them")
    };
    let body: Vec<String> = body.iter().map(|b| format!("  {b}")).collect();
    let svg = format!(
        "<svg xmlns=\"http://www.w3.org/2000/svg\" width=\"{w:.1}mm\" height=\"{h:.1}mm\"\n     viewBox=\"0 0 {w:.1} {h:.1}\" role=\"img\"\n     aria-label=\"{label}\">\n  <!-- DISPLAY ONLY - not a cut file. Generated by bell-section.rs from {name}. -->\n  <rect width=\"{w:.1}\" height=\"{h:.1}\" fill=\"{bore}\"/>\n{}\n  <line x1=\"{m:.1}\" y1=\"{cy:.1}\" x2=\"{:.1}\" y2=\"{cy:.1}\" stroke=\"{axis}\" stroke-width=\"0.6\" stroke-dasharray=\"6 3\"/>\n  <text x=\"{m:.1}\" y=\"{:.1}\" font-family=\"ui-sans-serif,system-ui,sans-serif\" font-size=\"7\" fill=\"#334155\">{n} rings · ø{:.0} bore to ø{:.1} rim · {l:.0}mm long</text>\n</svg>\n",
        body.join("\n"),
        m + l * scale,
        h - 4.0,
        rings[0].0,
        rings[n - 1].1
    );
    write(&dst, &svg);
    println!("  {dst}: {n} rings, {}mm rise, {w:.0} x {h:.0}mm", g(rise));
}
